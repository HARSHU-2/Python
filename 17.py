# if else, elif statement
x = int(input("Enter value: "))
if x > 0:
    print("Positive")
elif x == 0:
    print("Zero")
else:
    print("Negative")

# while loop
print("Output of while loop")
count = 0
while count < 5:
    print(count)
    count += 1

# for loop
print("Print numbers using for loop")
for i in range(5):
    print(i)

